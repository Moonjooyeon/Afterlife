function collapseGuide(input) {
  const raw = input.raw || {};
  const f = COLLAPSE[raw.temp];
  if (f) return f(raw.tempDir);
  if (["원수", "라이벌"].includes(raw.relation))
    return "관계가 적대적이다. 오열 대신 분노·조소·부정으로 버티다가, 싸울 상대가 사라진 공백에서 무너진다. 화해로 바꾸지 않는다.";
  return "관계의 온도를 스스로 해석해서 무너지는 방식 자체를 그 관계에 맞게 정한다.";
}

function buildPrompt(mode, input) {
  const seedFinal = { s: pick(SEEDS.finalSpeaker), t: pick(SEEDS.finalTechnique) };
  let sys = COMMON_RULES.replace("{FINAL_SPEAKER}", seedFinal.s).replace("{FINAL_TECHNIQUE}", seedFinal.t);
  sys += `
[이번 관계의 무너짐]
${collapseGuide(input)}
마지막 문장도 이 관계의 결을 유지한다. 증오·경쟁 관계라면 다정하게 끝내지 않는다.
`;
  sys += mode === "pair"
    ? PAIR_SPEC
    : SOLO_SPEC.replace("{DEATH_PRINCIPLE}", pick(SEEDS.deathPrinciple)).replace("{DISCOVER_TIMING}", pick(SEEDS.discoverTiming));

  const lines = [
    `떠난 사람(故): ${input.deadName} / ${mode === "pair" ? "상대를" : "받을 사람을"} 부르는 호칭·말투: ${input.deadVoice}`,
    mode === "pair"
      ? `남은 사람: ${input.livingName} / 호칭·말투: ${input.livingVoice}`
      : `받을 사람: ${input.livingName} / 받을 사람이 떠난 사람을 부르는 호칭·말투: ${input.livingVoice}`,
    `세계관 연도 표기: ${input.era}`,
    ...Object.entries(input.choices || {}).map(([k, v]) => `${k}: ${v}`),
    `키워드: ${input.keyword || "없음"}`,
    `서사·설정: ${input.story || "없음"}`,
  ];
  return { system: sys, user: lines.join("\n") };
}

